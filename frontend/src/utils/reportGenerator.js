/**
 * Generates a clean text/markdown summary suitable for sharing on messaging apps or email.
 */
export function generateTextSummary({
  expenses,
  totalSpent,
  formatCurrency,
  user,
  periodLabel = 'All Time',
  categoryStats = [],
}) {
  const dateStr = new Date().toLocaleDateString(undefined, {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  });

  let text = `📊 EXPENSSOR FINANCIAL REPORT\n`;
  text += `━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n`;
  text += `👤 Generated by: ${user?.name || 'User'}${user?.email ? ` (${user.email})` : ''}\n`;
  text += `📅 Date: ${dateStr}\n`;
  text += `⏱ Period: ${periodLabel}\n`;
  text += `💰 Total Spending: ${formatCurrency(totalSpent)}\n`;
  text += `🔢 Transactions: ${expenses.length}\n\n`;

  if (categoryStats.length > 0) {
    text += `📂 SPENDING BY CATEGORY:\n`;
    categoryStats.forEach((cat) => {
      text += `  • ${cat.name}: ${formatCurrency(cat.total)} (${cat.percentage.toFixed(1)}%)\n`;
    });
    text += `\n`;
  }

  if (expenses.length > 0) {
    text += `📝 RECENT TRANSACTIONS:\n`;
    expenses.slice(0, 10).forEach((exp) => {
      const d = new Date(exp.date).toLocaleDateString();
      text += `  • [${d}] ${exp.title} - ${formatCurrency(exp.amount)} (${exp.category})\n`;
    });
    if (expenses.length > 10) {
      text += `  ... and ${expenses.length - 10} more transactions.\n`;
    }
  }

  text += `\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n`;
  text += `Generated with Expenssor Expense Tracker`;

  return text;
}

